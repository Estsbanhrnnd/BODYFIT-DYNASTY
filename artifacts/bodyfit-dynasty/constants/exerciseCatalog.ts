/**
 * Retorna todos los ejercicios disponibles para una membresía dada
 */
export function getExercisesForTier(userTier: MembershipTierId | string | undefined): CatalogExercise[] {
  return RAW_CATALOG_EXERCISES.filter((ex) => hasTierAccess(userTier, ex.requiredTier));
}

/**
 * Comprueba si un ejercicio específico está desbloqueado para el usuario
 */
export function isExerciseUnlocked(exercise: CatalogExercise, userTier: MembershipTierId | string | undefined): boolean {
  return hasTierAccess(userTier, exercise.requiredTier);
}

/**
 * Calcula dinámicamente los porcentajes reales de desbloqueo del catálogo actual
 */
export function calculateCatalogStats() {
  const total = RAW_CATALOG_EXERCISES.length;
  const standardCount = RAW_CATALOG_EXERCISES.filter((e) => e.requiredTier === 'standard').length;
  const bronzeCount = RAW_CATALOG_EXERCISES.filter((e) => hasTierAccess('bronze', e.requiredTier)).length;
  const platinumCount = RAW_CATALOG_EXERCISES.filter((e) => hasTierAccess('platinum', e.requiredTier)).length;
  const goldenCount = total;

  return {
    total,
    standard: {
      count: standardCount,
      percent: Math.round((standardCount / total) * 100),
    },
    bronze: {
      count: bronzeCount,
      percent: Math.round((bronzeCount / total) * 100),
    },
    platinum: {
      count: platinumCount,
      percent: Math.round((platinumCount / total) * 100),
    },
    golden: {
      count: goldenCount,
      percent: 100,
    },
  };
}
